favorites = set()
def addWord(key,value):
    a=key[0].upper()
    if a in synop:
        synop[a][key]=value
    print("Word is Added !!")

    
def selWord(l):
    l=l.upper()
    if l in synop:
        for k,m in synop[l].items():
            print(k, "-->", m)
    else:
        print("Provide a valid letter!!")

def searchWord(word):
    a=word[0].upper()
    found=False
    if a in synop:
        p=synop[a]
        w=word.capitalize()
        if w in p:
            print(w,"   -->  ",p[w])
            found=True
    if found==False:
        print("Word is not found")

def updateWord(key,value):
    a=key[0].upper()
    found=False
    if a in synop:
        s=key.capitalize()
        p=synop[a]
        if s in p:
            p[s]=value
            found=True
            print("Word is Updated")
    if found==False:
        print("Word is not found")

def delWord(key):
    a=key[0].upper()
    found=False
    if a in synop:
        w=key.capitalize()
        p=synop[a]
        if w in p:
            p.pop(w)
            found=True
            print("Word has been deleted")
    if found==False:
        print("Word is not found")

def displayAll():
    for l, m in synop.items():
        print("-----",l,"-------")
        for k, n in m.items():
            print(k,"   --->   ",n)

def wordexist(word):
    a=word[0].upper()
    if a in synop:
        p=synop[a]
        w=word.capitalize()
        if w in p:
            print("The word is present")
        else:
            print("The word is not present")

def addFavorite(word):
    a = word[0].upper()
